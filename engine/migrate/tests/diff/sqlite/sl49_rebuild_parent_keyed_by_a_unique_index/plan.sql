create table new_users (id integer primary key, email text not null, name text check (length(name) > 0));
create table new_logins (id integer primary key, email text references new_users (email) on delete cascade);
create table new_sessions (id integer primary key, email text references new_logins (email));
create unique index new_users_email on new_users (email);
create unique index new_logins_email on new_logins (email);
insert into new_users (id, email, name) select id, email, name from users;
insert into new_logins (id, email) select id, email from logins;
insert into new_sessions (id, email) select id, email from sessions;
drop table sessions;
drop table logins;
drop table users;
