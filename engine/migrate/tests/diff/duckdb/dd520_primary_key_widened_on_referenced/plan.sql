create table users (id bigint, email varchar not null, name varchar, feeling mood, score integer default 0, primary key (id), unique (email));
create table posts (id integer, user_id bigint, title varchar, body varchar, created date default current_date, primary key (id), foreign key (user_id) references users (id));
