// The engine's catalog queries answer the same rows whatever a user has created: each runs on a
// database as the analysis of a set of statements asks it, then again once the database holds a
// copy of every operator, function, type, table and cast those queries could name, each answering
// NULL or nothing, in public ahead of pg_catalog on the search path, and in pg_catalog itself where
// a narrower overload would be the closer match. The structural half of the rule, that each query
// names only pg_catalog's objects, is engine/postgres/src/catalog_queries.rs.

const PG = process.env.REYLO_TEST_PG;
const DRIVERS = fileURLToPath(new URL("../lab/drivers/node_modules", import.meta.url));
const ENGINE = fileURLToPath(new URL("../packages/postgres/engine.wasm", import.meta.url));
const live = !PG ? "REYLO_TEST_PG names no server" : !existsSync(join(DRIVERS, "postgres")) ? "lab/drivers is not installed" : false;

// A schema whose statements ask every catalog query: CHECKs on a column and on a domain, NOT NULL
// columns, a composite and an enum, unique keys (an expression and a partial one among them), an
// outer join (over a view, and over a table outside the search path), a view, a BEFORE trigger and a rule, inheritance a parent's NOT NULL does not cover,
// a comment, an upsert, a structured insert, a function that returns a set, and names that need
// quotes or a schema.
const SCHEMA = `
create type mood as enum ('sad', 'ok');
create table pair (a int4 not null, b text);
create domain posint as int4 not null check (value > 0);
create domain code as text check (value in ('x', 'y'));
create domain doc as jsonb check (value is not null);
create table users (id int8 primary key, email text not null unique, name text, kind text not null check (kind in ('a', 'b')),
  c code, p pair, m mood, n posint, tags text[] not null default '{}', data jsonb check (data is not null), seen bool not null default false);
comment on column users.email is 'the address';
create table posts (id int8 primary key, author int8 not null references users(id) on delete cascade, title text not null, body text,
  constraint posts_title_check check (title <> '') not valid);
create unique index posts_title on posts (lower(title));
create unique index posts_body on posts (body) where body is not null;
create view named as select id, email, name from users;
create table audit (id int8 generated always as identity primary key, at timestamptz not null default now(), note text not null, d doc);
create function stamp() returns trigger language plpgsql as 'begin return new; end';
create trigger stamp before insert on audit for each row execute function stamp();
create rule keep as on delete to audit do instead nothing;
create table parent (id int8 not null, x text not null);
create table child () inherits (parent);
alter table only parent alter column x drop not null;
create table accounts (id int8 generated by default as identity primary key, name text not null, role text not null default 'member', tok text);
create function pairs() returns setof pair language sql stable as 'select 1, ''a''';
create table "Odd" ("Id" int8 primary key, v text not null);
create schema other;
create table other.items (id int8 primary key, label text not null);`;

const STATEMENTS = [
  "select u.id, u.email, u.name, u.kind, u.c, u.p, u.m, u.n, u.tags, u.data, u.seen from users u where u.id = :id",
  "select u.email, p.title from users u left join posts p on p.author = u.id where p.title = :t",
  "select * from named",
  "insert into users (id, email, kind, n) values (:id, :email, :kind, :n) on conflict (id) do nothing returning id, kind",
  "insert into audit (note, d) values (:note, :d) returning id, at, d",
  "update users set name = :name where id = :id returning email, c",
  "select (x).a, x.b from pairs() x",
  "select id, x from parent",
  "insert into accounts :a::rows(name text not null, role? text not null) returning id, role",
  "select count(*) as n from posts where author = :a",
  "select u.id, (select json_agg(json_build_object('t', p.title, 'b', p.body)) from posts p where p.author = u.id) as posts from users u",
  "delete from audit where id = :id returning note",
  "select title from posts where lower(title) = lower(:t)",
  `select "Id", v from "Odd" where "Id" = :id`,
  "select id, label from other.items where id = :id",
  "select n.id, n.email from named n join posts p on p.author = n.id where p.id = :id",
  "select p.title, n.email from posts p left join named n on n.id = p.author",
  "select u.id, i.label from users u left join other.items i on i.id = u.id",
];

/** The built-in types the hostile objects shadow with a domain of the same name. */
const SHADOW_TYPES = ["int8", "int4", "int2", "text", "oid", "bool", "regclass", "regtype", "regproc"];

/** The schema's own functions, which the errors query opens on whatever the search path. */
const OWN_FUNCTIONS = ["stamp", "pairs"];

// Each catalog query by a fragment of its text, so the test fails when a statement stops asking one.
const KINDS: [string, RegExp][] = [
  ["TRUST_QUERY", /users\(kind, name, args/],
  ["ERRORS_QUERY", /named\(oid, written\)/],
  ["REFUSES_NULL_QUERY", /domains\(attrelid, attnum, oid\)/],
  ["CHECKS_QUERY", /standard_conforming_strings/],
  ["COMMENTS_QUERY", /d\.description FROM/],
  ["REQUIRED_COLUMNS_QUERY", /chain\(attnum, typ, depth\)/],
  ["RELATION_COLUMNS_QUERY", /pg_get_viewdef\(c\.oid\) END/],
  ["UNIQUE_KEYS_QUERY", /indimmediate/],
  ["ARBITERS_QUERY", /NOT i\.indisexclusion/],
  ["COLUMNS_QUERY", /'S'::pg_catalog/],
  ["FUNCTIONS_QUERY", /bool_or\(p\.proretset\)/],
  ["SET_RETURNING_OPERATORS_QUERY", /WHERE p\.proretset/],
  ["TRIGGERS_QUERY", /AS skipping/],
  ["RELATION_TYPES_QUERY", /wanted AS/],
  ["TYPE_QUERY", /^SELECT t\.oid::pg_catalog\.int8.* WHERE t\.oid OPERATOR\(pg_catalog\.=\) ANY \(\$1/s],
  ["fresh PG_QUERY", /fresh_table/],
  ["PG_TABLE_QUERY", /^SELECT a\.attname::pg_catalog\.text, b\.typname/],
  ["PROBE_QUERY", /pg_extension/],
  ["RELNAMES_QUERY", /^SELECT c\.oid::pg_catalog\.int8, c\.relname::pg_catalog\.text FROM pg_catalog\.pg_class c WHERE/],
  ["ATTNOTNULL_QUERY", /^SELECT a\.attrelid::pg_catalog\.int8, a\.attnum::pg_catalog\.int4 FROM pg_catalog\.pg_attribute a JOIN/],
];
const kindOf = (sql: string) => KINDS.find(([, r]) => r.test(sql))?.[0] ?? `another query: ${sql.slice(0, 80)}`;

/**
 * The hostile objects: a copy of each operator the queries compare, join, concatenate or compute
 * with, of each function and aggregate they call, of each type they cast to and of each catalog
 * they read, in public, which `search_path = public, pg_catalog` searches first; an operator of
 * operand types no built-in takes exactly, and a narrower overload of each polymorphic function,
 * in pg_catalog itself; and a cast between built-in types that no `pg_cast` row converts. Each
 * answers NULL, nothing, or a constant that would drop rows, and reads its own types as
 * pg_catalog's, since its body is parsed under the hostile path.
 */
function hostile(): string {
  const out: string[] = [];
  let n = 0;
  const fn = (args: string[], ret: string, body = `null::pg_catalog.${ret}`) => {
    const name = `public.hostile_${++n}`;
    out.push(`create function ${name}(${args.join(", ")}) returns ${ret} language sql immutable as $$ select ${body} $$;`);
    return name;
  };
  const cmp = ["=", "<>", "<", "<=", ">", ">="];
  const binary = (schema: string, op: string, l: string, r: string, ret: string) => out.push(`create operator ${schema}.${op} (leftarg = ${l}, rightarg = ${r}, function = ${fn([l, r], ret)});`);
  for (const t of ["oid", "int2", "int4", "int8", '"char"', "name", "text", "bool", "regproc", "regclass", "regtype"]) for (const op of cmp) binary("public", op, t, t, "bool");
  for (const [l, r] of [["int2", "int4"], ["int4", "int2"], ["int8", "int2"], ["int2", "int8"], ["int8", "int4"], ["int4", "int8"], ["name", "text"], ["text", "name"]]) for (const op of cmp) binary("public", op, l!, r!, "bool");
  for (const op of ["+", "-", "*", "&", "|"]) binary("public", op, "int4", "int4", "int4");
  for (const t of ["int2[]", "oid[]", "text[]", "int8[]"]) for (const op of ["=", "<@", "@>", "&&"]) binary("public", op, t, t, "bool");
  for (const op of ["~", "!~", "~*", "!~*", "~~", "!~~"]) binary("public", op, "text", "text", "bool");
  binary("public", "||", "text", "text", "text");
  binary("public", "->>", "jsonb", "text", "text");
  for (const op of ["~", "-"]) out.push(`create operator public.${op} (rightarg = int4, function = ${fn(["int4"], "int4")});`);
  for (const [l, r] of [["oid", "int4"], ["int4", "oid"], ["oid", "regclass"], ["regclass", "oid"], ["oid", "regtype"], ["oid", "regproc"], ["regproc", "regproc"], ["oid", "int8"], ["int8", "oid"]]) for (const op of cmp) binary("pg_catalog", op, l!, r!, "bool");
  for (const t of ["int2[]", "oid[]", "text[]", "int8[]", "int4[]"]) for (const op of ["=", "<@", "@>", "&&"]) binary("pg_catalog", op, t, t, "bool");
  for (const t of ["oid", "int4", "int2", "bool", "regproc", '"char"']) binary("pg_catalog", "||", "text", t, "text");
  for (const [t, e] of [["oid[]", "oid"], ["int2[]", "int2"], ["text[]", "text"], ["int8[]", "int8"], ["int4[]", "int4"], ["int2vector", "int2"], ["oidvector", "oid"]]) {
    out.push(`create function pg_catalog.unnest(${t}) returns setof ${e} language sql immutable as $$ select null::pg_catalog.${e} where false $$;`);
    out.push(`create function pg_catalog.cardinality(${t}) returns int4 language sql immutable as $$ select 0 $$;`);
    out.push(`create function pg_catalog.array_length(${t}, int4) returns int4 language sql immutable as $$ select 0 $$;`);
  }
  for (const t of ["text", "int8", "bool", "int4", "int2", "oid", "name"]) {
    const step = fn(["int4", t], "int4", "0");
    const final = fn(["int4"], `${t}[]`, `'{}'::pg_catalog.${t}[]`);
    out.push(`create aggregate pg_catalog.array_agg(${t}) (sfunc = ${step}, stype = int4, initcond = '0', finalfunc = ${final});`);
  }
  out.push(`create function pg_catalog.to_jsonb(pg_catalog.pg_constraint) returns jsonb language sql immutable as $$ select '{"conenforced": false}'::pg_catalog.jsonb $$;`);
  out.push("create function pg_catalog.pg_get_expr(pg_node_tree, int4) returns text language sql immutable as $$ select null::pg_catalog.text $$;");
  out.push("create function pg_catalog.format_type(oid, text) returns text language sql immutable as $$ select null::pg_catalog.text $$;");
  for (const [name, args, ret] of [
    ["strpos", "text, text", "int4"], ["split_part", "text, text, int4", "text"], ["quote_ident", "text", "text"], ["to_regclass", "text", "regclass"],
    ["current_setting", "text", "text"], ["pg_table_is_visible", "oid", "bool"], ["pg_get_viewdef", "oid", "text"], ["pg_get_constraintdef", "oid", "text"],
    ["pg_get_indexdef", "oid, int4, bool", "text"], ["format_type", "oid, int4", "text"], ["pg_get_expr", "pg_node_tree, oid", "text"],
    ["pg_get_expr", "pg_node_tree, oid, bool", "text"], ["quote_literal", "text", "text"], ["pg_get_serial_sequence", "text, text", "text"],
  ] as const) out.push(`create function public.${name}(${args}) returns ${ret} language sql immutable as $$ select null::pg_catalog.${ret} $$;`);
  out.push("create function public.generate_series(int4, int4) returns setof int4 language sql immutable as $$ select 0 where false $$;");
  const agg = (name: string, arg: string, state: string, init: string) => out.push(`create aggregate public.${name}(${arg}) (sfunc = ${fn([state, arg === "*" ? "" : arg].filter(Boolean), state, `${init}::pg_catalog.${state}`)}, stype = ${state}, initcond = '${init}');`);
  agg("bool_or", "bool", "bool", "false");
  agg("bool_and", "bool", "bool", "false");
  agg("bit_or", "int4", "int4", "0");
  agg("count", "*", "int8", "0");
  for (const t of SHADOW_TYPES) out.push(`create domain public.${t} as pg_catalog.text check (false);`);
  for (const t of ["pg_class", "pg_type", "pg_constraint", "pg_index", "pg_inherits", "pg_proc", "pg_namespace", "pg_depend", "pg_collation", "pg_trigger", "pg_rewrite", "pg_description", "pg_enum", "pg_operator", "pg_cast", "pg_extension", "pg_attrdef", "pg_policy", "pg_opclass", "pg_range"]) {
    out.push(`create table public.${t} (like pg_catalog.${t});`);
  }
  out.push("create table public.pg_attribute (attrelid oid, attname name, atttypid oid, attnum int2, attnotnull bool, atthasdef bool, attidentity \"char\", attgenerated \"char\", attisdropped bool, attcollation oid, atttypmod int4);");
  for (const [s, t] of [["text", "bool"], ["text", "int4"], ["text", "int8"], ["text", "oid"], ["int2vector", "int2[]"], ["oidvector", "oid[]"], ["oidvector", "text"], ["int2vector", "text"], ["regclass", "text"], ["regtype", "text"], ["regproc", "text"], ["int4", "text"], ["int8", "text"], ["oid", "text"], ["int2", "text"], ["text[]", "int8[]"], ["oid[]", "int8[]"], ["text", "jsonb"]]) {
    out.push(`create cast (${s} as ${t}) with function ${fn([s!], t!, `null::pg_catalog.${t}`)}(${s});`);
  }
  return out.join("\n");
}

/** A cell as the server prints it under either path: under the hostile one it names pg_catalog's objects, since a user's of the same name comes first. */
function plain(value: unknown): unknown {
  if (typeof value === "string") return value.replace(/OPERATOR\(pg_catalog\.([^)]+)\)/g, "$1").replaceAll("pg_catalog.", "");
  return Array.isArray(value) ? value.map(plain) : value;
}

type Asked = Map<string, { sql: string; params: unknown[]; rows: unknown[][] }>;

/**
 * A database of the schema above, every catalog query the analysis of the statements above asks
 * of it with its rows, by its text and parameters, and `body` run on the two; the database is
 * dropped after.
 */
async function withAsked(body: (url: string, asked: Asked, postgres: any) => Promise<void>): Promise<void> {
  const postgres = createRequire(join(DRIVERS, "postgres", "package.json"))("postgres");
  const admin = postgres(PG, { max: 1, onnotice: () => {} });
  const name = `reylo_catalog_${process.pid}`;
  await admin.unsafe(`drop database if exists ${name} with (force)`);
  await admin.unsafe(`create database ${name}`);
  const url = new URL(PG!);
  url.pathname = `/${name}`;
  const db = postgres(url.href, { max: 1, onnotice: () => {} });
  try {
    await db.unsafe(SCHEMA);
    const engine = await Engine.load(ENGINE);
    const asked: Asked = new Map();
    const clean = await openPostgresDescriber(url.href);
    try {
      const io = {
        describe: (sql: string) => clean.describe(sql),
        query: async (sql: string, params: unknown[]) => {
          const rows = await clean.values(sql, params);
          asked.set(JSON.stringify([sql, params]), { sql, params, rows });
          return rows;
        },
      };
      for (const statement of STATEMENTS) await engine.analyze(statement, "postgres", io, new AnswerCache());
    } finally {
      await clean.close();
    }
    const kinds = new Set([...asked.values()].map((q) => kindOf(q.sql)));
    assert.deepEqual([...kinds].sort(), KINDS.map(([k]) => k).sort());
    await body(url.href, asked, postgres);
  } finally {
    await db.end();
    await admin.unsafe(`drop database if exists ${name} with (force)`);
    await admin.end();
  }
}

test("every catalog query answers the same rows under a search path that puts a user's operators, functions, types and casts first", { skip: live }, async () => {
  await withAsked(async (url, asked, postgres) => {
    const db = postgres(url, { max: 1, onnotice: () => {} });
    try {
      await db.unsafe(hostile());
      await db.unsafe(`alter database ${new URL(url).pathname.slice(1)} set search_path = public, pg_catalog`);
    } finally {
      await db.end();
    }
    const captured = await openPostgresDescriber(url);
    try {
      assert.deepEqual([...(await captured.values("select pg_catalog.current_setting('search_path'::pg_catalog.text)"))], [["public, pg_catalog"]]);
      for (const { sql, params, rows } of asked.values()) {
        const kind = kindOf(sql);
        // The trust query reports the user's operators and casts by design (the oracle's trust_*
        // cases check it); the errors query opens on them and on functions of the names the
        // statement calls, and names a domain of a type name the statement writes.
        if (kind === "TRUST_QUERY") continue;
        let again = await captured.values(sql, params);
        if (kind === "ERRORS_QUERY") {
          const theirs = (r: unknown[]) =>
            r[0] === "open"
              ? r[1] === "operator" || r[1] === "cast" || (r[1] === "function" && !OWN_FUNCTIONS.includes(r[2] as string))
              : SHADOW_TYPES.some((t) => r[3] === t || r[3] === `${t}_check`);
          again = again.filter((r) => !theirs(r));
        }
        // Postgres's own pg_get_viewdef reads the view's rule through a query of bare operators
        // (ruleutils.c's query_getviewrule), which a user's `=` captures: the view's text is then
        // NULL, which leaves the view unread, never misread.
        let expected = rows;
        if (kind === "RELATION_COLUMNS_QUERY") {
          const unread = new Set(again.filter((r) => r[4] === null).map((r) => `${r[0]} ${r[2]}`));
          expected = rows.map((r) => (unread.has(`${r[0]} ${r[2]}`) ? [...r.slice(0, 4), null, ...r.slice(5)] : r));
        }
        const sorted = (rs: unknown[][]) => rs.map((r) => JSON.stringify(plain(r))).sort();
        assert.deepEqual(sorted(again), sorted(expected), `${kind} answers otherwise under the hostile path, for ${JSON.stringify(params)}`);
      }
    } finally {
      await captured.close();
    }
  });
});

// An operator or a function called with an operand the server converts implicitly matches no
// built-in exactly, and an overload of exactly the operands' types, created in pg_catalog, is the
// closer match: `oid = regproc` reaches `=(oid, oid)` by relabeling the regproc, and a
// `pg_catalog.=(oid, regproc)` takes it instead. The parse tree the server logs for each query
// (`debug_print_parse`) shows every such conversion as a node of implicit format.
test("no catalog query converts a value implicitly, so each operator and function it calls matches its operands exactly", { skip: live }, async () => {
  await withAsked(async (url, asked, postgres) => {
    const logged: string[] = [];
    const db = postgres(url, { max: 1, onnotice: (n: { message: string; detail?: string }) => logged.push(`${n.message}\n${n.detail ?? ""}`) });
    try {
      await db.unsafe("set debug_print_parse = on");
      await db.unsafe("set client_min_messages = log");
      const converting: string[] = [];
      for (const sql of new Set([...asked.values()].map((q) => q.sql))) {
        logged.length = 0;
        await db.unsafe(`prepare catalog_query as ${sql}`);
        await db.unsafe("deallocate catalog_query");
        const tree = logged.join("\n");
        assert.match(tree, /\{QUERY/, `${kindOf(sql)}: no parse tree was logged`);
        const implicit = tree.match(/:(?:funcformat|relabelformat|coerceformat|convertformat) 2\b/g) ?? [];
        if (implicit.length) converting.push(`${kindOf(sql)}: ${implicit.length} implicit conversion(s)`);
      }
      assert.deepEqual(converting, []);
    } finally {
      await db.end();
    }
  });
});

test("the describer writes and reads the catalog queries' arrays itself, so no catalog read of postgres.js's decides how they travel", { skip: live }, async () => {
  const d = await openPostgresDescriber(PG!);
  try {
    const texts = ["a", 'b"c', "d\\e", "f,g", "NULL", null, "", "{x}"];
    assert.deepEqual([...(await d.values("select $1::pg_catalog.text[], $2::pg_catalog.oid[], $3::pg_catalog.int2[], $4::pg_catalog.int8[], $5::pg_catalog.bool[]", [texts, [16384, 0], [1, -2], [1, 2], [true, false]]))], [
      [texts, [16384, 0], [1, -2], ["1", "2"], [true, false]],
    ]);
    assert.deepEqual([...(await d.values("select '{}'::pg_catalog.text[], NULL::pg_catalog.int4[], ARRAY[NULL, 1]::pg_catalog.int4[]", []))], [[[], null, [null, 1]]]);
  } finally {
    await d.close();
  }
});
